-- ADVS initial schema (implementation plan rev. 2, §4).
-- Tables follow the class diagram; enums are TEXT + CHECK constraints.

CREATE TABLE categories (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         text NOT NULL UNIQUE,                 -- e.g. CAT-GEN
  name         text NOT NULL UNIQUE,
  description  text,
  is_active    boolean NOT NULL DEFAULT true,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
  id                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                  text NOT NULL,
  email                 text NOT NULL UNIQUE,         -- stored lower-case
  phone                 text,
  password_hash         text NOT NULL,
  role                  text NOT NULL CHECK (role IN ('APPLICANT', 'VERIFIER', 'ADMINISTRATOR')),
  is_active             boolean NOT NULL DEFAULT true,
  assigned_category_id  integer REFERENCES categories (id),
  created_at            timestamptz NOT NULL DEFAULT now(),
  updated_at            timestamptz NOT NULL DEFAULT now(),
  -- Verifier.assignedCategory: only verifiers have one
  CHECK (role = 'VERIFIER' OR assigned_category_id IS NULL)
);

-- Category 1 --<> 1..* ChecklistItem (composition)
CREATE TABLE checklist_items (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id    integer NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
  document_type  text NOT NULL,
  is_mandatory   boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (category_id, document_type)
);

CREATE SEQUENCE application_number_seq;

-- Applicant 1 -- 0..* Application
CREATE TABLE applications (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_number  text NOT NULL UNIQUE,          -- ADM-<year>-<NNN>
  applicant_id        integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  category_id         integer REFERENCES categories (id),
  overall_status      text NOT NULL DEFAULT 'PENDING'
                      CHECK (overall_status IN ('PENDING', 'UNDER_REVIEW', 'COMPLETED', 'REJECTED')),
  submission_date     timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX applications_applicant_idx ON applications (applicant_id);

-- Application 1 --<> 0..* Document
CREATE TABLE documents (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id     integer NOT NULL REFERENCES applications (id) ON DELETE CASCADE,
  checklist_item_id  integer NOT NULL REFERENCES checklist_items (id),
  file_name          text NOT NULL,
  file_path          text NOT NULL,
  mime_type          text NOT NULL,
  size_bytes         integer NOT NULL,
  status             text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
  remarks            text,                              -- latest remark
  current_version    integer NOT NULL DEFAULT 1,
  upload_date        timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (application_id, checklist_item_id)
);
CREATE INDEX documents_status_upload_idx ON documents (status, upload_date);

-- Document 1 --<> 1..* DocumentFile (every uploaded version)
CREATE TABLE document_files (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id  integer NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  version      integer NOT NULL,
  file_name    text NOT NULL,
  file_path    text NOT NULL,
  mime_type    text NOT NULL,
  size_bytes   integer NOT NULL,
  uploaded_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (document_id, version)
);

-- Document 1 -- 0..* VerificationRecord; also serves as VerificationHistory (FR-020)
CREATE TABLE verification_records (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id    integer NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  verifier_id    integer NOT NULL REFERENCES users (id),
  status         text NOT NULL CHECK (status IN ('PENDING', 'VERIFIED', 'REJECTED')),
  remarks        text,
  is_correction  boolean NOT NULL DEFAULT false,
  decision_date  timestamptz NOT NULL DEFAULT now(),
  -- BR-004: a remark is required unless the document is verified
  CHECK (status = 'VERIFIED' OR length(trim(coalesce(remarks, ''))) > 0)
);
CREATE INDEX verification_records_document_idx ON verification_records (document_id);

CREATE TABLE notifications (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id  integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  type          text NOT NULL
                CHECK (type IN ('STATUS_UPDATE', 'MISSING_DOCUMENT', 'REMARK_ADDED', 'NEW_SUBMISSION')),
  message       text NOT NULL,
  link          text,
  status        text NOT NULL DEFAULT 'GENERATED' CHECK (status IN ('GENERATED', 'SENT', 'FAILED', 'READ')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  read_at       timestamptz
);
CREATE INDEX notifications_recipient_idx ON notifications (recipient_id, status);

CREATE TABLE system_settings (
  key         text PRIMARY KEY,
  value       jsonb NOT NULL,
  updated_by  integer REFERENCES users (id) ON DELETE SET NULL,
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE audit_logs (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id     integer REFERENCES users (id) ON DELETE SET NULL,
  action       text NOT NULL,
  entity_type  text,
  entity_id    text,
  details      jsonb,
  created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_logs_created_idx ON audit_logs (created_at);
